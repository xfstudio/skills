import assert from 'node:assert/strict';
import {authorizationDecision,requireMerchant,requirePreservedScope} from '../scripts/authorization.mjs';
const cfg={account:'Account',publicAppId:'123',merchant:'Target',ensureAuthorization:true};
const found={listed:true,statusLabels:['定向','已上架']};
const full={complete:true,shops:['Other']};
const pending={account:'Account',publicAppId:'123',merchant:'Target',phase:'authorization_unknown'};
assert.equal(authorizationDecision(cfg,found,full,[]),'add_missing');
assert.equal(authorizationDecision({...cfg,ensureAuthorization:false},found,full,[]),'authorization_missing');
assert.equal(authorizationDecision(cfg,found,full,[pending]),'authorization_unknown');
assert.equal(authorizationDecision(cfg,found,{complete:true,shops:['Other','Target']},[pending]),'already_authorized');
assert.equal(authorizationDecision(cfg,{listed:false,statusLabels:['定向','已下架']},null,[]),'not_listed');
assert.equal(authorizationDecision(cfg,{listed:true,statusLabels:['公开','已上架']},null,[]),'public_listing');
for(const auth of [{complete:false,shops:[]},{complete:true,shops:['Other','Other']},{complete:true,shops:[null]}])assert.throws(()=>authorizationDecision(cfg,found,auth,[]));
for(const merchant of ['', ' Target','Target,Other','Target\nOther','Target；Other','Target\tOther'])assert.throws(()=>requireMerchant(merchant));
assert.doesNotThrow(()=>requireMerchant('斐川茶园旗舰店'));
assert.doesNotThrow(()=>requirePreservedScope(full,{complete:true,shops:['Target','Other']},'Target'));
for(const after of [{complete:false,shops:['Target','Other']},{complete:true,shops:['Target']},{complete:true,shops:['Other']},{complete:true,shops:['Other','Target','Unexpected']}])assert.throws(()=>requirePreservedScope(full,after,'Target'));
assert.equal(authorizationDecision(cfg,found,full,[{...pending,publicAppId:'456'}]),'add_missing');
assert.equal(authorizationDecision(cfg,found,full,[{...pending,merchant:'Another'}]),'add_missing');
console.log('Authorization scope, incomplete pagination, no-repeat, and offline/public guards passed');
